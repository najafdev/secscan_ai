class Severity(str, Enum):
    CRITICAL = "Critical"
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"
    INFO = "Info"


@dataclass
class Finding:
    """A security finding discovered during assessment."""

    title: str
    severity: Severity
    description: str
    evidence: str = ""
    recommendation: str = ""
    tool: str = ""
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "title": self.title,
            "severity": self.severity.value,
            "description": self.description,
            "evidence": self.evidence,
            "recommendation": self.recommendation,
            "tool": self.tool,
            "timestamp": self.timestamp,
        }


@dataclass
class AgentStep:
    """A single step in the agent's execution."""

    step_num: int
    action: str  # "execute" | "finding" | "analysis" | "complete"
    description: str
    tool_result: Optional[ToolResult] = None
    finding: Optional[Finding] = None
    ai_analysis: str = ""
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "step_num": self.step_num,
            "action": self.action,
            "description": self.description,
            "tool_result": self.tool_result.to_dict() if self.tool_result else None,
            "finding": self.finding.to_dict() if self.finding else None,
            "ai_analysis": self.ai_analysis,
            "timestamp": self.timestamp,
        }


@dataclass
class GeneratedScript:
    """A custom script generated by the agent for the current target."""

    name: str
    language: str
    content: str
    description: str = ""
    category: str = "custom"
    target: str = ""
    path: str = ""
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "language": self.language,
            "content": self.content,
            "description": self.description,
            "category": self.category,
            "target": self.target,
            "path": self.path,
            "timestamp": self.timestamp,
        }


class AgentMode:
    """
    Autonomous cybersecurity testing agent.

    Flow:
    1. User provides target and scope
    2. Agent plans the assessment
    3. Agent executes tools step by step
    4. Agent analyzes results and adapts
    5. Agent reports findings
    """

    def __init__(
        self,
        engine: AIEngine,
        config: HackBotConfig,
        on_step: Optional[Callable[[AgentStep], None]] = None,
        on_confirm: Optional[Callable[[str, str], bool]] = None,
        on_output: Optional[Callable[[str], None]] = None,
        on_token: Optional[Callable[[str], None]] = None,
    ):
        self.engine = engine
        self.config = config
        self.on_step = on_step
        self.on_token = on_token

        self.runner = ToolRunner(
            allowed_tools=config.agent.allowed_tools,
            timeout=config.agent.timeout,
            safe_mode=config.agent.safe_mode,
            auto_confirm=config.agent.auto_confirm,
            sudo_mode=config.agent.sudo_mode,
            sudo_password=config.agent.sudo_password,
            on_confirm=on_confirm,
            on_output=on_output,
        )
        self.installer = ToolInstaller(self.runner)

        self.conversation: Optional[Conversation] = None
        self.target: str = ""
        self.scope: str = ""
        self.steps: List[AgentStep] = []
        self.findings: List[Finding] = []
        self.scripts: List[GeneratedScript] = []
        self.is_running: bool = False
        self._step_count: int = 0
        self._last_response: str = ""
        self._was_truncated: bool = False
        self._command_history: Dict[str, int] = {}
        self._nudge_count: int = 0

        # Vulnerability database
        self.vulndb = VulnDB()
        self._assessment_id: Optional[int] = None

        # CVE / NVD intelligence engine
        self.cve_engine = CVELookup(nvd_api_key=config.agent.nvd_api_key)

        # Zero-day discovery engine
        self.zeroday = ZeroDayEngine()

        # Memory & summarization
        self.memory = MemoryManager()
        self.session_id = self.memory.new_session_id("agent")
        self.summarizer = ConversationSummarizer(
            engine=engine,
            max_messages=20,  # Smaller threshold for agent (tool outputs are large)
            keep_recent=6,
        )

        # RAG vector memory (graceful fallback)
        self.rag: RAGMemory = get_rag_memory()
        self._rag_enabled = config.rag.enabled and self.rag.is_available()
        if self._rag_enabled:
            logger.debug("RAG memory active for agent mode")

    def start(self, target: str, scope: str = "", instructions: str = "") -> str:
        """
        Start a new assessment against a target.

        Args:
            target: Target IP, domain, or URL
            scope: Scope limitations
            instructions: Additional instructions for the agent
        """
        self.target = target
        self.scope = scope
        self.steps = []
        self.findings = []
        self.scripts = []
        self._step_count = 0
        self._command_history = {}
        self._nudge_count = 0
        self.is_running = True

        # Validate sudo access upfront if sudo_mode is on
        if self.config.agent.sudo_mode:
            ok, msg = self.runner.check_sudo()
            if not ok:
                logger.warning("Sudo validation failed: %s", msg)
                return f"⚠️ Sudo mode is enabled but sudo access failed: {msg}\n\nDisable sudo_mode or configure sudo_password in settings, then retry."

        # Create assessment in vulnerability database
        try:
            tools_used = [t for t, avail in self.runner.get_available_tools().items() if avail]
            self._assessment_id = self.vulndb.create_assessment(
                target=target,
                scope=scope,
                tools_used=tools_used,
            )
        except Exception as exc:
            logger.warning("VulnDB: failed to create assessment: %s", exc)
            self._assessment_id = None

        self.conversation = create_conversation("agent", target, language=self.config.ui.language)

        # Add scope and available tools context
        available_tools = self.runner.get_available_tools()
        installed = [t for t, avail in available_tools.items() if avail]
        not_installed = [t for t, avail in available_tools.items() if not avail]

        context = f"""Assessment Context:
- Target: {target}
- Scope: {scope or 'Full assessment as authorized'}
- Safe Mode: {'Enabled' if self.config.agent.safe_mode else 'Disabled'}
- Available Tools: {', '.join(installed) if installed else 'None detected'}
- Unavailable Tools: {', '.join(not_installed) if not_installed else 'None'}
- Max Steps: {self.config.agent.max_steps}
- NVD CVE Intelligence: {'Enabled (API key configured — fast rate limit)' if self.config.agent.nvd_api_key else 'Enabled (no API key — slower rate limit)'}
- Zero-Day Engine: Enabled (response anomaly detection, smart fuzzing, exploit chain analysis)
- Fuzz Payload Categories: {', '.join(c['name'] for c in self.zeroday.get_payload_categories())}
"""

        # Add custom plugin context
        if get_plugin_manager is not None:
            try:
                pm = get_plugin_manager()
                plugin_desc = pm.get_agent_tool_descriptions()
                if plugin_desc:
                    context += plugin_desc + "\n"
            except Exception:
                pass

        # ── RAG: inject prior intelligence for this target ────────────
        if self._rag_enabled:
            try:
                prior_intel = self.rag.get_target_context(
                    target,
                    max_results=self.config.rag.max_results + 3,
                    max_chars=self.config.rag.max_context_tokens * 4,
                )
                if prior_intel:
                    context += f"\n{prior_intel}\n"
            except Exception as exc:
                logger.debug("RAG target context retrieval failed: %s", exc)

        context += f"""
{f'Additional Instructions: {instructions}' if instructions else ''}

Begin the assessment. Start with reconnaissance and work methodically through each phase.
Explain your reasoning at each step."""

        self.conversation.add("user", context)

        # Get initial plan from AI
        try:
            response = self.engine.chat(
                self.conversation,
                stream=bool(self.on_token),
                on_token=self.on_token,
            )
        except Exception as e:
            logger.error("Agent start failed: %s", e)
            self.is_running = False
            error_msg = f"Failed to connect to AI model: {e}"
            self.conversation.add("assistant", error_msg)
            self._auto_save()
            return error_msg

        self.conversation.add("assistant", response)
        self._last_response = response
        self._was_truncated = self._detect_truncation(response)

        # Parse and execute any actions in the initial response
        actions = self._parse_actions(response)

        # If the AI described a plan but didn't emit JSON action blocks, nudge it
        if not actions and len(response) > 100 and self._should_nudge(response):
            actions = self._nudge_for_actions()

        # Process actions in a loop — including execute actions from follow-up analysis
        analysis = self._process_actions_loop(response, actions)
        if analysis:
            response = response + "\n\n" + analysis

        # Auto-save
        self._auto_save()

        return response

    def step(self, user_input: str = "") -> tuple[str, bool]:
        """
        Execute the next step in the assessment.

        Returns:
            (ai_response, is_complete)
        """
        if not self.is_running or not self.conversation:
            return "No active assessment. Use 'start' first.", True

        if self._step_count >= self.config.agent.max_steps:
            self.is_running = False
            return "Maximum steps reached. Generating final report...", True

        self._step_count += 1
        self._nudge_count = 0

        # Summarize conversation if it's getting too long (reduces hallucination)
        if self.summarizer.needs_summarization(self.conversation.messages):
            self.summarizer.summarize(self.conversation)

        # If user provided feedback, add it
        if user_input:
            self.conversation.add("user", user_input)
        else:
            self.conversation.add("user", "Continue with the next step of the assessment.")

        # Get AI response
        try:
            response = self.engine.chat(
                self.conversation,
                stream=bool(self.on_token),
                on_token=self.on_token,
            )
        except Exception as e:
            logger.error("Agent step failed: %s", e)
            error_msg = f"AI request failed: {e}"
            self.conversation.add("assistant", error_msg)
            self._auto_save()
            return error_msg, False

        self.conversation.add("assistant", response)
        self._last_response = response
        self._was_truncated = self._detect_truncation(response)

        # Parse and execute any actions in the response
        actions = self._parse_actions(response)

        # If the AI described a plan but didn't emit JSON action blocks, nudge it
        if not actions and len(response) > 100 and self._should_nudge(response):
            actions = self._nudge_for_actions()

        # Process actions in a loop — including execute actions from follow-up analysis
        is_complete = False
        for action in actions:
            if action.get("action") == "complete":
                is_complete = True
                break

        if is_complete:
            self.is_running = False
            self._auto_save()
            return response, True

        analysis = self._process_actions_loop(response, actions)
        if analysis:
            self._auto_save()
            return analysis, not self.is_running

        self._auto_save()
        return response, False

    def continue_response(
        self,
        on_token: Optional[Callable[[str], None]] = None,
    ) -> tuple[str, bool]:
        """Continue a response that was cut off mid-stream."""
        if not self.conversation:
            return "No active conversation to continue.", True

        self.conversation.add("user", CONTINUE_PROMPT)

        token_cb = on_token or self.on_token
        response = self.engine.chat(
            self.conversation,
            stream=bool(token_cb),
            on_token=token_cb,
        )
        self.conversation.add("assistant", response)
        self._last_response = response
        self._was_truncated = self._detect_truncation(response)

        # Parse any actions in the continuation
        actions = self._parse_actions(response)
        for action in actions:
            if action.get("action") == "finding":
                self._record_finding(action)
            elif action.get("action") == "script":
                self._save_script(action)
            elif action.get("action") == "generate_report":
                self._generate_report(action)
            elif action.get("action") == "complete":
                self.is_running = False
                self._auto_save()
                return response, True

        self._auto_save()
        return response, False

    @property
    def was_truncated(self) -> bool:
        """Check if the last response was likely truncated."""
        return self._was_truncated

    def _detect_truncation(self, text: str) -> bool:
        """Heuristically detect if a response was truncated."""
        if not text or len(text) < 50:
            return False
        stripped = text.rstrip()
        if not stripped:
            return False
        last_char = stripped[-1]
        open_blocks = stripped.count("```") % 2 != 0
        ends_incomplete = last_char not in ".!?\"')]}>`\n*-" and not stripped.endswith("---")
        return open_blocks or ends_incomplete

    def _auto_save(self) -> None:
        """Auto-save current agent session."""
        if not self.conversation:
            return
        try:
            messages = [
                {"role": m.role, "content": m.content, "timestamp": m.timestamp}
                for m in self.conversation.messages
                if m.role != "system"
            ]
            findings = [f.to_dict() for f in self.findings]
            self.memory.auto_save_agent(
                session_id=self.session_id,
                messages=messages,
                target=self.target,
                findings=findings,
                scripts=[s.to_dict() for s in self.scripts],
                steps=[s.to_dict() for s in self.steps],
            )
        except Exception:
            pass

    def run_command(self, command: str, explanation: str = "") -> ToolResult:
        """Manually execute a command through the agent."""
        tool_name = command.split()[0] if command.split() else "unknown"
        result = self.runner.execute(command, tool_name=tool_name, explanation=explanation)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="execute",
            description=explanation or command,
            tool_result=result,
        )
        self.steps.append(step)

        if self.on_step:
            self.on_step(step)

        return result

    def ask(self, question: str) -> str:
        """Ask the agent a question in the context of the current assessment."""
        if not self.conversation:
            self.conversation = create_conversation(
                "agent", self.target, language=self.config.ui.language
            )

        self.conversation.add("user", question)
        response = self.engine.chat(
            self.conversation,
            stream=bool(self.on_token),
            on_token=self.on_token,
        )
        self.conversation.add("assistant", response)
        return response

    def stop(self) -> str:
        """Stop the current assessment and generate a summary."""
        self.is_running = False

        # Finalize assessment in vulnerability database
        if self._assessment_id is not None:
            try:
                self.vulndb.finish_assessment(
                    self._assessment_id,
                    total_steps=len(self.steps),
                    total_findings=len(self.findings),
                )
                self.vulndb.take_risk_snapshot(self.target)
            except Exception as exc:
                logger.warning("VulnDB: failed to finish assessment: %s", exc)

        if self.conversation:
            self.conversation.add(
                "user",
                "The assessment has been stopped. Please provide a summary of findings so far.",
            )
            try:
                response = self.engine.chat(self.conversation, stream=False)
                self.conversation.add("assistant", response)
                return response
            except Exception as exc:
                fallback = (
                    self.get_findings_summary()
                    if self.findings
                    else "Assessment stopped (no findings recorded)."
                )
                logger.warning("Failed to generate AI summary on stop: %s", exc)
                return f"Assessment stopped. AI summary unavailable (API error).\n\n{fallback}"
        return "No active assessment."

    def get_findings_summary(self) -> str:
        """Get a markdown summary of all findings."""
        if not self.findings:
            return "No findings recorded yet."

        lines = ["# Security Findings\n"]
        by_severity: Dict[str, List[Finding]] = {}
        for f in self.findings:
            sev = f.severity.value
            by_severity.setdefault(sev, []).append(f)

        stats = {s: len(fs) for s, fs in by_severity.items()}
        lines.append(
            f"**Total: {len(self.findings)}** | "
            + " | ".join(f"{s}: {c}" for s, c in stats.items())
        )
        lines.append("")

        for severity in ["Critical", "High", "Medium", "Low", "Info"]:
            findings = by_severity.get(severity, [])
            if not findings:
                continue
            lines.append(f"\n## {severity} ({len(findings)})\n")
            for i, f in enumerate(findings, 1):
                lines.append(f"### {i}. {f.title}")
                lines.append(f"\n{f.description}")
                if f.evidence:
                    lines.append(f"\n**Evidence:**\n```\n{f.evidence}\n```")
                if f.recommendation:
                    lines.append(f"\n**Recommendation:** {f.recommendation}")
                lines.append("")

        return "\n".join(lines)

    def _process_actions_loop(
        self,
        ai_response_text: str,
        actions: List[Dict[str, Any]],
        max_rounds: int = 5,
    ) -> str:
        """
        Execute actions and keep processing follow-up actions from AI analysis.

        When the AI responds to tool results with new execute actions (e.g. retrying
        a failed command with different flags), this loop continues execution instead
        of dropping back to the REPL prompt.

        Returns the last AI analysis text, or "" if nothing was executed.
        """
        if not self.conversation:
            return ""

        last_analysis = ""
        failure_counts: Dict[tuple[str, int, str], int] = {}

        for _round in range(max_rounds):
            results_text = []
            repeated_failures: List[ToolResult] = []
            seen_this_round: set = set()

            for action in actions:
                atype = action.get("action")
                if atype == "execute":
                    cmd = (action.get("command") or "").strip()

                    # Skip duplicate commands within the same round
                    if cmd in seen_this_round:
                        logger.info("Skipping duplicate command in same round: %s", cmd)
                        continue
                    seen_this_round.add(cmd)

                    # Skip commands already executed too many times this session
                    if self._command_history.get(cmd, 0) >= 2:
                        skip_msg = (
                            f"**[Skipped]** Command `{cmd}` already executed "
                            f"{self._command_history[cmd]} times. "
                            f"Try a different approach or tool."
                        )
                        logger.info(
                            "Skipping repeated command: %s (count=%d)",
                            cmd,
                            self._command_history[cmd],
                        )
                        results_text.append(skip_msg)
                        continue

                    ai_analysis_clean = self._extract_thoughts(ai_response_text)
                    result_text, tool_result = self._execute_action(
                        action, ai_analysis=ai_analysis_clean
                    )
                    results_text.append(result_text)

                    if not tool_result.success:
                        signature = (
                            tool_result.command.strip(),
                            tool_result.return_code,
                            (tool_result.stderr or "").strip(),
                        )
                        failure_counts[signature] = failure_counts.get(signature, 0) + 1
                        if failure_counts[signature] >= 2:
                            repeated_failures.append(tool_result)
                elif atype == "finding":
                    ai_analysis_clean = self._extract_thoughts(ai_response_text)
                    self._record_finding(action, ai_analysis=ai_analysis_clean)
                elif atype == "script":
                    ai_analysis_clean = self._extract_thoughts(ai_response_text)
                    script_result = self._save_script(action, ai_analysis=ai_analysis_clean)
                    results_text.append(script_result)
                elif atype == "generate_report":
                    ai_analysis_clean = self._extract_thoughts(ai_response_text)
                    report_result = self._generate_report(action, ai_analysis=ai_analysis_clean)
                    results_text.append(report_result)
                elif atype == "fuzz":
                    fuzz_result = self._process_fuzz_action(action)
                    results_text.append(fuzz_result)
                elif atype == "analyze_anomaly":
                    anomaly_result = self._process_anomaly_action(action)
                    results_text.append(anomaly_result)
                elif atype == "chain_exploits":
                    chain_result = self._process_chain_action()
                    results_text.append(chain_result)
                elif atype == "install":
                    install_result = self._process_install_action(action)
                    results_text.append(install_result)
                elif atype == "complete":
                    ai_analysis_clean = self._extract_thoughts(ai_response_text)
                    step = AgentStep(
                        step_num=len(self.steps) + 1,
                        action="complete",
                        description="Assessment completed.",
                        ai_analysis=ai_analysis_clean,
                    )
                    self.steps.append(step)
                    if self.on_step:
                        self.on_step(step)
                    self.is_running = False
                    return last_analysis

            # If no commands were executed this round, we're done
            if not results_text:
                break

            # Loop guard: stop repeated identical failures in the same run loop.
            if repeated_failures:
                failed = repeated_failures[0]
                loop_msg = (
                    "Stopped automatic retries to prevent an execution loop. "
                    "The same command failed repeatedly.\n\n"
                    f"Command: `{failed.command}`\n"
                    f"Error: `{(failed.stderr or 'Unknown error').strip()}`\n\n"
                    "Please adjust configuration/tool availability and continue with a different command."
                )
                self.conversation.add("assistant", loop_msg)
                return loop_msg

            # Feed results back to AI
            result_msg = "\n\n---\n\n".join(results_text)
            self.conversation.add("user", f"Tool execution results:\n\n{result_msg}")

            try:
                analysis = self.engine.chat(
                    self.conversation,
                    stream=bool(self.on_token),
                    on_token=self.on_token,
                )
            except Exception as e:
                logger.error("Agent analysis failed: %s", e)
                analysis = f"AI analysis request failed: {e}"

            self.conversation.add("assistant", analysis)
            self._last_response = analysis
            ai_response_text = analysis
            actions = self._parse_actions(analysis)
            self._was_truncated = self._detect_truncation(analysis)
            last_analysis = analysis

            # Parse follow-up actions (including execute) from the analysis
            actions = self._parse_actions(analysis)

            # If no more actions, stop the loop
            if not actions:
                break

        return last_analysis

    def _extract_thoughts(self, text: str) -> str:
        """Strip JSON action blocks from the text to isolate the agent's reasoning."""
        import re

        cleaned = re.sub(r"```json\s*\{.*?\}\s*```", "", text, flags=re.DOTALL)
        cleaned = re.sub(r'\{"action"\s*:\s*.*\}', "", cleaned)
        return cleaned.strip()

    def _parse_actions(self, text: str) -> List[Dict[str, Any]]:
        """Extract JSON action blocks from AI response."""
        actions: List[Dict[str, Any]] = []
        allowed_actions = {
            "execute",
            "finding",
            "script",
            "complete",
            "generate_report",
            "fuzz",
            "analyze_anomaly",
            "chain_exploits",
            "install",
        }
        decoder = json.JSONDecoder()
        seen_spans: set[tuple[int, int]] = set()

        idx = 0
        while idx < len(text):
            start = text.find("{", idx)
            if start == -1:
                break

            try:
                obj, end = decoder.raw_decode(text[start:])
            except json.JSONDecodeError:
                idx = start + 1
                continue

            span = (start, start + end)
            idx = start + end

            if span in seen_spans:
                continue
            seen_spans.add(span)

            if not isinstance(obj, dict):
                continue

            action_name = obj.get("action")
            if isinstance(action_name, str) and action_name in allowed_actions:
                actions.append(obj)

        return actions

    # Pattern to detect tool/command mentions in AI responses
    _TOOL_PATTERN = re.compile(
        r"\b(nmap|nikto|sqlmap|gobuster|dirb|hydra|curl|wget|ping|traceroute|"
        r"dig|whois|masscan|ffuf|wfuzz|burp|nuclei|metasploit|msfconsole|"
        r"feroxbuster|amass|subfinder|httpx|testssl|sslscan|enum4linux|"
        r"smbclient|wpscan|john|hashcat)\b",
        re.IGNORECASE,
    )

    def _should_nudge(self, response: str) -> bool:
        """Only nudge if response mentions tool names and we haven't nudged this step."""
        if self._nudge_count >= 1:
            return False
        self._nudge_count += 1
        return bool(self._TOOL_PATTERN.search(response))

    def _nudge_for_actions(self) -> List[Dict[str, Any]]:
        """
        If the AI described commands but didn't emit JSON action blocks,
        send a follow-up nudge asking it to output the proper format.

        Returns any actions parsed from the nudge response.
        """
        if not self.conversation:
            return []

        nudge_msg = (
            "I see you described your plan, but you did not include any JSON action blocks. "
            "I cannot execute commands unless they are in the required JSON format.\n\n"
            "Please output the FIRST command you want to run as a JSON action block now:\n"
            "```json\n"
            '{"action": "execute", "tool": "<tool_name>", "command": "<full_command>", "explanation": "<why>"}\n'
            "```\n\n"
            "Do NOT describe the command in text — just output the JSON block."
        )
        self.conversation.add("user", nudge_msg)

        try:
            response = self.engine.chat(
                self.conversation,
                stream=bool(self.on_token),
                on_token=self.on_token,
            )
        except Exception as e:
            logger.error("Nudge request failed: %s", e)
            return []

        self.conversation.add("assistant", response)
        self._last_response = response

        return self._parse_actions(response)

    def _process_install_action(self, action: Dict[str, Any]) -> str:
        """Autonomously install a missing security tool (allowlist-bounded)."""
        tool = (action.get("tool") or "").strip()
        if not tool:
            return "**[install]** No tool specified."

        # Allowlist bound (unless the user opted into arbitrary installs).
        if not self.config.agent.allow_arbitrary_install and not self.runner.is_tool_allowed(tool):
            return (
                f"**[install]** `{tool}` is not in the allowlist; cannot auto-install. "
                f"Use a different tool or ask the user to install it manually."
            )

        if resolve_tool_path(tool):
            return f"**[install]** `{tool}` is already installed — proceed to use it."

        plan = self.installer.plan_install(tool)
        if plan is None:
            return (
                f"**[install]** No install recipe for `{tool}` on this system "
                f"(unmapped tool or no supported package manager available). "
                f"Try a different tool."
            )

        # Respect safe_mode: one confirmation before installing.
        if self.config.agent.safe_mode and not self.config.agent.auto_confirm:
            confirm = getattr(self.runner, "on_confirm", None)
            cmd_str = " ".join(plan.command)
            reason = f"INSTALL {tool} via {plan.manager}"
            if confirm and not confirm(cmd_str, reason):
                return f"**[install]** User declined installation of `{tool}`."

        result: InstallResult = self.installer.install(plan)
        if result.success:
            return f"**[install]** SUCCESS — {result.message}. You may now use `{tool}`."
        detail = (result.stderr or result.stdout or "").strip()[:500]
        sudo_hint = ""
        if plan.needs_sudo and not self.runner.sudo_mode:
            sudo_hint = " (system installs need --sudo / sudo_mode; it appears disabled)"
        return f"**[install]** FAILED — {result.message}{sudo_hint}.\n```\n{detail}\n```"

    def _execute_action(
        self, action: Dict[str, Any], ai_analysis: str = ""
    ) -> tuple[str, ToolResult]:
        """Execute a tool action and return (formatted_result, raw_tool_result)."""
        command = action.get("command", "")
        tool = action.get("tool", command.split()[0] if command else "unknown")
        explanation = action.get("explanation", "")

        # ── Sanitize command before execution ──────────────────────────
        # Strip any AI-generated sudo prefix — the runner's _apply_sudo()
        # will re-add it if sudo_mode is enabled.
        command = ToolRunner._strip_sudo_prefix(command.strip())

        # If the command still has no recognizable tool binary (e.g., the
        # AI emitted just flags like "--target 1.2.3.4"), reconstruct it
        # using the tool field from the JSON action block.
        if command:
            first_token = command.split()[0]
            if first_token.startswith("-") and tool and tool not in ("unknown", "sudo"):
                command = f"{tool} {command}"

        # Track command execution count for loop prevention
        cmd_key = command.strip()
        self._command_history[cmd_key] = self._command_history.get(cmd_key, 0) + 1

        result = self.runner.execute(command, tool_name=tool, explanation=explanation)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="execute",
            description=explanation,
            tool_result=result,
            ai_analysis=ai_analysis,
        )
        self.steps.append(step)

        if self.on_step:
            self.on_step(step)

        status = "SUCCESS" if result.success else "FAILED"
        output = (
            f"**[{tool}]** {status} (exit={result.return_code}, {result.duration:.1f}s)\n"
            f"Command: `{command}`\n\n"
            f"```\n{result.output[:5000]}\n```"
        )

        # Auto CVE enrichment for nmap scans
        if result.success and tool.lower() in ("nmap", "nmap.exe"):
            cve_intel = self._enrich_with_cves(result.output)
            if cve_intel:
                output += f"\n\n{cve_intel}"

        # Auto zero-day anomaly analysis on all tool output
        try:
            zeroday_intel = self.zeroday.enrich_tool_output(result.output, tool_name=tool)
            if zeroday_intel:
                output += f"\n\n{zeroday_intel}"
        except Exception as exc:
            logger.debug("Zero-day enrichment failed: %s", exc)

        # ── RAG: store tool output ───────────────────────────────────
        if self._rag_enabled:
            try:
                self.rag.store_tool_output(
                    command=command,
                    stdout=result.stdout or "",
                    stderr=result.stderr or "",
                    target=self.target,
                    tool=tool,
                    success=result.success,
                )
            except Exception as exc:
                logger.debug("RAG tool output store failed: %s", exc)

        return output, result

    def _save_script(self, action: Dict[str, Any], ai_analysis: str = "") -> str:
        """Persist a generated script/exploit and return a formatted summary."""
        content = str(action.get("content", "") or "").strip()
        if not content:
            return "**[Script]** FAILED: Missing `content` in script action."

        language = str(action.get("language", "text") or "text").strip().lower()
        category = str(action.get("category", "custom") or "custom").strip().lower()
        name = str(action.get("name", "generated_script") or "generated_script").strip()
        description = str(action.get("description", "") or "").strip()

        ext_map = {
            "python": "py",
            "bash": "sh",
            "shell": "sh",
            "sh": "sh",
            "powershell": "ps1",
            "javascript": "js",
            "js": "js",
            "ruby": "rb",
            "perl": "pl",
            "php": "php",
            "go": "go",
            "rust": "rs",
            "c": "c",
            "cpp": "cpp",
        }
        ext = ext_map.get(language, "txt")
        safe_name = re.sub(r"[^a-zA-Z0-9._-]+", "_", name).strip("._") or "generated_script"

        scripts_dir = REPORTS_DIR / "scripts"
        scripts_dir.mkdir(parents=True, exist_ok=True)
        ts = time.strftime("%Y%m%d_%H%M%S")
        filename = f"{safe_name}_{ts}.{ext}"
        script_path = scripts_dir / filename

        try:
            with open(script_path, "w", encoding="utf-8") as f:
                f.write(content)
        except Exception as exc:
            return f"**[Script]** FAILED to save script: {exc}"

        script = GeneratedScript(
            name=name,
            language=language,
            content=content,
            description=description,
            category=category,
            target=self.target,
            path=str(script_path),
        )
        self.scripts.append(script)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="script",
            description=description or f"Generated script: {name}",
            ai_analysis=ai_analysis,
        )
        self.steps.append(step)
        if self.on_step:
            self.on_step(step)

        preview = content[:2500]
        if len(content) > 2500:
            preview += "\n... [truncated]"

        return (
            f"**[Script:{category}]** SAVED\n"
            f"Name: `{name}`\n"
            f"Language: `{language}`\n"
            f"Path: `{script_path}`\n\n"
            f"```{language}\n{preview}\n```"
        )

    def _enrich_with_cves(self, nmap_output: str) -> str:
        """
        Auto-enrich nmap scan results with CVE intelligence from NVD.

        Parses the nmap output for discovered services / versions and looks up
        known CVEs, returning a formatted markdown report that is appended to
        the tool result fed back to the AI.
        """
        try:
            service_cves = self.cve_engine.parse_nmap_and_lookup(
                nmap_output,
                max_per_service=5,
            )
        except Exception as exc:
            logger.warning("CVE auto-enrichment failed: %s", exc)
            return ""

        if not service_cves:
            return ""

        report = CVELookup.format_nmap_cve_report(service_cves)

        # Also persist high-severity CVEs as findings
        for service_key, cves in service_cves.items():
            for cve in cves:
                if cve.cvss_score >= 7.0:
                    finding = Finding(
                        title=f"{cve.cve_id} — {service_key}",
                        severity=Severity.CRITICAL if cve.cvss_score >= 9.0 else Severity.HIGH,
                        description=cve.description,
                        evidence=f"CVSS {cve.cvss_score} ({cve.cvss_vector})",
                        recommendation=f"Patch or mitigate {cve.cve_id}. See: {cve.references[0] if cve.references else 'NVD'}",
                        tool="nmap+nvd",
                    )
                    self.findings.append(finding)
                    if self._assessment_id is not None:
                        try:
                            self.vulndb.add_finding(
                                self._assessment_id,
                                finding.to_dict(),
                                target=self.target,
                            )
                        except Exception:
                            pass

        # Log enrichment summary
        total = sum(len(c) for c in service_cves.values())
        high_crit = sum(1 for cves in service_cves.values() for c in cves if c.cvss_score >= 7.0)
        logger.info(
            "CVE enrichment: %d vulns across %d services (%d high/critical)",
            total,
            len(service_cves),
            high_crit,
        )

        return report

