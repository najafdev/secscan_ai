    def _process_fuzz_action(self, action: Dict[str, Any]) -> str:
        """Process a fuzz action from the AI agent."""
        target_url = action.get("target_url", "").strip()
        parameter = action.get("parameter", "").strip()
        categories = action.get("categories", [])
        explanation = action.get("explanation", "Smart fuzzing")

        if not target_url:
            return "**[Fuzz]** FAILED: target_url is required."

        # Get payloads
        payloads: list = []
        if categories:
            for cat in categories[:5]:  # Max 5 categories
                payloads.extend(self.zeroday.get_fuzz_payloads(category=cat, max_payloads=10))
        else:
            payloads = self.zeroday.get_fuzz_payloads(max_payloads=30)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="fuzz",
            description=f"Fuzzing {target_url} (param: {parameter or 'body'}, {len(payloads)} payloads)",
        )
        self.steps.append(step)
        if self.on_step:
            self.on_step(step)

        # Run fuzzing via curl for each payload (capped for safety)
        results_text = [
            f"**[Fuzz]** Testing {len(payloads)} payloads against `{target_url}`\n",
            f"Parameter: `{parameter or 'request body'}` | Categories: {', '.join(categories) or 'all'}\n",
        ]

        interesting_count = 0
        for i, payload in enumerate(payloads[:20]):  # Cap at 20 for performance
            # Use curl to send the payload
            safe_payload = payload.replace("'", "'\\''")
            if parameter:
                cmd = f"curl -sk -o /dev/null -w '%{{http_code}} %{{time_total}} %{{size_download}}' -d '{parameter}={safe_payload}' '{target_url}'"
            else:
                cmd = f"curl -sk -o /dev/null -w '%{{http_code}} %{{time_total}} %{{size_download}}' -d '{safe_payload}' '{target_url}'"

            result = self.runner.execute(
                cmd, tool_name="curl", explanation=f"Fuzz payload {i+1}/{len(payloads)} ({explanation})"
            )

            if result.success and result.stdout.strip():
                parts = result.stdout.strip().split()
                status = parts[0] if parts else "0"
                resp_time = parts[1] if len(parts) > 1 else "0"
                resp_size = parts[2] if len(parts) > 2 else "0"

                # Check for anomalous responses
                is_interesting = status in ("500", "502", "503") or float(resp_time) > 5.0
                if is_interesting:
                    interesting_count += 1
                    results_text.append(
                        f"  ⚠️ **Payload {i+1}**: status={status} time={resp_time}s size={resp_size} "
                        f"payload=`{payload[:60]}...`"
                    )

        results_text.append(
            f"\n**Summary:** {interesting_count} interesting responses out of {min(len(payloads), 20)} tested"
        )
        if interesting_count > 0:
            results_text.append(
                "⚠️ Interesting responses detected — investigate manually with full response body."
            )

        return "\n".join(results_text)

    def _process_anomaly_action(self, action: Dict[str, Any]) -> str:
        """Process an analyze_anomaly action from the AI agent."""
        response_body = action.get("response_body", "")
        context = action.get("context", "")

        if not response_body:
            return "**[Anomaly Analysis]** FAILED: response_body is required."

        anomalies = self.zeroday.analyze_response(response_body)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="analyze_anomaly",
            description=f"Anomaly analysis: {len(anomalies)} signals found ({context[:50]})",
        )
        self.steps.append(step)
        if self.on_step:
            self.on_step(step)

        if not anomalies:
            return f"**[Anomaly Analysis]** No anomaly signals detected in the response.\nContext: {context}"

        # Auto-record high-severity anomalies as findings
        from hackbot.core.zeroday import ZeroDayEngine

        report = ZeroDayEngine.format_anomalies_report(anomalies)

        for a in anomalies:
            if a.severity in ("Critical", "High") and a.confidence >= 0.7:
                finding = Finding(
                    title=f"Zero-Day Signal: {a.indicator}",
                    severity=Severity.HIGH if a.severity == "High" else Severity.CRITICAL,
                    description=a.description,
                    evidence=a.evidence,
                    recommendation=a.exploit_potential,
                    tool="zeroday-engine",
                )
                self.findings.append(finding)

        return f"**[Anomaly Analysis]** {len(anomalies)} signals detected:\n\n{report}"

    def _process_chain_action(self) -> str:
        """Process a chain_exploits action — build exploit chains from current findings."""
        if not self.findings:
            return "**[Exploit Chains]** No findings available to build chains from."

        findings_dicts = [f.to_dict() for f in self.findings]
        chains = self.zeroday.build_exploit_chains(findings_dicts)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="chain_exploits",
            description=f"Exploit chain analysis: {len(chains)} chains identified",
        )
        self.steps.append(step)
        if self.on_step:
            self.on_step(step)

        from hackbot.core.zeroday import ZeroDayEngine

        report = ZeroDayEngine.format_chains_report(chains)

        # Record critical chains as findings
        for chain in chains:
            if chain.overall_severity == "Critical":
                finding = Finding(
                    title=f"Exploit Chain: {chain.title}",
                    severity=Severity.CRITICAL,
                    description=chain.overall_impact,
                    evidence=f"Chain: {' → '.join(s['finding'] for s in chain.chain_steps)}",
                    recommendation=", ".join(chain.mitigations),
                    tool="zeroday-engine",
                )
                self.findings.append(finding)

        return report

    def _record_finding(self, action: Dict[str, Any], ai_analysis: str = "") -> None:
        """Record a security finding."""
        try:
            severity = Severity(action.get("severity", "Info"))
        except ValueError:
            severity = Severity.INFO

        finding = Finding(
            title=action.get("title", "Untitled Finding"),
            severity=severity,
            description=action.get("description", ""),
            evidence=action.get("evidence", ""),
            recommendation=action.get("recommendation", ""),
        )

        self.findings.append(finding)

        # Persist to vulnerability database
        if self._assessment_id is not None:
            try:
                self.vulndb.add_finding(
                    self._assessment_id,
                    finding.to_dict(),
                    target=self.target,
                )
            except Exception as exc:
                logger.warning("VulnDB: failed to store finding: %s", exc)

        # ── RAG: store finding ───────────────────────────────────────
        if self._rag_enabled:
            try:
                finding_data = finding.to_dict()
                finding_data["target"] = self.target
                self.rag.store_finding(finding_data)
            except Exception as exc:
                logger.debug("RAG finding store failed: %s", exc)

        step = AgentStep(
            step_num=len(self.steps) + 1,
            action="finding",
            description=f"[{severity.value}] {finding.title}",
            finding=finding,
            ai_analysis=ai_analysis,
        )
        self.steps.append(step)

        if self.on_step:
            self.on_step(step)

    def _generate_report(self, action: Dict[str, Any], ai_analysis: str = "") -> str:
        """Generate a PDF report from current findings."""
        if not HAS_REPORTLAB:
            msg = "PDF report generation unavailable — reportlab not installed."
            step = AgentStep(
                step_num=len(self.steps) + 1,
                action="report",
                description=msg,
                ai_analysis=ai_analysis,
            )
            self.steps.append(step)
            if self.on_step:
                self.on_step(step)
            return msg

        findings_data = [f.to_dict() for f in self.findings]
        tool_history = [r.to_dict() for r in self.runner.history]
        scripts = [s.to_dict() for s in self.scripts]

        # Build compliance data if requested and findings exist
        compliance_data = None
        if action.get("include_compliance", True) and findings_data:
            try:
                from hackbot.core.compliance import ComplianceMapper

                mapper = ComplianceMapper()
                creport = mapper.map_findings(findings_data, target=self.target)
                if creport.mappings:
                    compliance_data = creport.to_dict()
            except Exception:
                pass

        # Build ATT&CK mapping data
        attack_data = None
        if findings_data:
            try:
                from hackbot.core.attack import AttackMapper

                amapper = AttackMapper()
                areport = amapper.map_findings(
                    findings_data,
                    target=self.target,
                    tool_history=tool_history,
                )
                if areport.mappings:
                    attack_data = areport.to_dict()
            except Exception:
                pass

        try:
            gen = PDFReportGenerator(include_raw=True)
            path = gen.generate(
                target=self.target,
                findings=findings_data,
                tool_history=tool_history,
                scripts=scripts,
                scope=self.scope,
                summary="",
                start_time=self.steps[0].timestamp if self.steps else 0,
                compliance_data=compliance_data,
                attack_data=attack_data,
                agent_steps=[s.to_dict() for s in self.steps],
            )

            step = AgentStep(
                step_num=len(self.steps) + 1,
                action="report",
                description=f"PDF report saved: {path}",
                ai_analysis=ai_analysis,
            )
            self.steps.append(step)
            if self.on_step:
                self.on_step(step)

            return f"**[Report]** PDF report generated successfully.\nSaved to: `{path}`"

        except Exception as e:
            msg = f"Report generation failed: {e}"
            step = AgentStep(
                step_num=len(self.steps) + 1,
                action="report",
                description=msg,
            )
            self.steps.append(step)
            if self.on_step:
                self.on_step(step)
            return msg

    def save_assessment(self) -> Path:
        """Save the full assessment data."""
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        ts = time.strftime("%Y%m%d_%H%M%S")
        path = REPORTS_DIR / f"assessment_{self.target.replace('/', '_')}_{ts}.json"

        data = {
            "target": self.target,
            "scope": self.scope,
            "timestamp": time.time(),
            "steps": len(self.steps),
            "findings": [f.to_dict() for f in self.findings],
            "tool_history": [r.to_dict() for r in self.runner.history],
            "scripts": [s.to_dict() for s in self.scripts],
        }

        with open(path, "w") as f:
            json.dump(data, f, indent=2)

        return path
